"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Loader2, Trash2 } from "lucide-react";
import { useState } from "react";
import { toast } from "sonner";
import { AiBrandIcon } from "@/components/brand";
import { clientApi } from "@/lib/api";

type AiCredential = {
  provider: string;
  status: string;
  key_mask: string | null;
  mode: string;
  last_validated_at: string | null;
  verified_model?: string | null;
};

function formatValidatedAt(iso: string | null | undefined): string | null {
  if (!iso) return null;
  try {
    return new Date(iso).toLocaleString();
  } catch {
    return null;
  }
}

export default function AiSettingsPage() {
  const client = useQueryClient();
  const [apiKey, setApiKey] = useState("");
  const [verifiedModel, setVerifiedModel] = useState<string | null>(null);
  const [replacing, setReplacing] = useState(false);

  const { data, isLoading } = useQuery({
    queryKey: ["ai-credentials"],
    queryFn: () => clientApi<AiCredential>("/me/ai-credentials"),
  });

  const isConnected = data?.status === "CONNECTED";
  const isInvalid = data?.status === "INVALID";
  const hasConnection = isConnected || isInvalid;
  const showKeyForm = !hasConnection || replacing;
  const pastedKey = apiKey.trim();

  const save = useMutation({
    mutationFn: () =>
      clientApi<AiCredential>("/me/ai-credentials", {
        method: "PUT",
        body: JSON.stringify({
          api_key: apiKey,
          verified_model: verifiedModel || undefined,
        }),
      }),
    onSuccess: (result) => {
      setApiKey("");
      setVerifiedModel(null);
      setReplacing(false);
      client.invalidateQueries({ queryKey: ["ai-credentials"] });
      toast.success(
        result.verified_model
          ? `Gemini connected · ${result.verified_model}`
          : "Gemini connected",
      );
    },
    onError: (e: Error) => toast.error(e.message),
  });

  const testPastedKey = useMutation({
    mutationFn: async (key: string) => {
      const res = await fetch("/api/test-gemini", {
        method: "POST",
        credentials: "include",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ api_key: key }),
      });
      const body = await res.json().catch(() => null);
      if (!res.ok) {
        throw new Error(body?.error?.message || "Gemini test failed.");
      }
      return body as { ok: boolean; verified_model?: string };
    },
    onSuccess: (result) => {
      if (result.verified_model) setVerifiedModel(result.verified_model);
      toast.success(
        `Gemini OK · model ${result.verified_model || "unknown"}. Click Save & connect to apply.`,
      );
    },
    onError: (e: Error) => toast.error(e.message),
  });

  const testStoredKey = useMutation({
    mutationFn: () =>
      clientApi<AiCredential>("/me/ai-credentials", {
        method: "PUT",
        body: JSON.stringify({ test_only: true }),
      }),
    onSuccess: (result) => {
      client.invalidateQueries({ queryKey: ["ai-credentials"] });
      toast.success(`Gemini OK · model ${result.verified_model || "unknown"}`);
    },
    onError: (e: Error) => toast.error(e.message),
  });

  const removeKey = useMutation({
    mutationFn: () =>
      clientApi<AiCredential>("/me/ai-credentials", { method: "DELETE" }),
    onSuccess: () => {
      setApiKey("");
      setVerifiedModel(null);
      setReplacing(false);
      client.invalidateQueries({ queryKey: ["ai-credentials"] });
      toast.success("API key removed. Paste a new key to connect again.");
    },
    onError: (e: Error) => toast.error(e.message),
  });

  const handleRemove = () => {
    if (
      !window.confirm(
        "Remove this Gemini API key? Ask AI will stop working until you connect a new key.",
      )
    ) {
      return;
    }
    removeKey.mutate();
  };

  const handleTestNewKey = () => {
    if (pastedKey.length < 10) {
      toast.error("Paste an API key before testing.");
      return;
    }
    testPastedKey.mutate(pastedKey);
  };

  const validatedLabel = formatValidatedAt(data?.last_validated_at);

  return (
    <section className="settings-card p-6 sm:p-8">
      <div className="flex items-center gap-3">
        <AiBrandIcon size={28} />
        <div>
          <h2 className="font-semibold">AI Connections</h2>
          <p className="text-sm text-muted">Connect Gemini for Ask AI</p>
        </div>
      </div>
      <p className="mt-1 max-w-lg text-sm leading-6 text-muted">
        Connect your Gemini API key for grounded Ask AI answers. Ask AI requires a valid Gemini
        key — answers are generated by Google Gemini using your library content.
      </p>

      {isLoading ? (
        <p className="mt-5 text-sm text-muted">Loading connection…</p>
      ) : hasConnection ? (
        <div className="mt-5 rounded-xl border border-border bg-surface-muted px-4 py-3">
          <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
            <div className="flex min-w-0 items-start gap-3">
              <GeminiMark />
              <div className="min-w-0">
                <div className="flex flex-wrap items-center gap-2">
                  <p className="text-sm font-medium text-foreground">Google Gemini</p>
                  <span
                    className={`rounded-full px-2 py-0.5 text-[11px] font-semibold uppercase tracking-wide ${
                      isConnected
                        ? "bg-emerald-100 text-emerald-800 dark:bg-emerald-950 dark:text-emerald-200"
                        : "bg-amber-100 text-amber-800 dark:bg-amber-950 dark:text-amber-200"
                    }`}
                  >
                    {data?.status}
                  </span>
                </div>
                <p className="mt-1 text-xs text-muted">
                  {data?.key_mask ? `Key ${data.key_mask}` : "Key saved"}
                  {data?.verified_model ? ` · model ${data.verified_model}` : ""}
                </p>
                {validatedLabel ? (
                  <p className="mt-0.5 text-xs text-muted">Last validated {validatedLabel}</p>
                ) : null}
              </div>
            </div>
            <div className="flex shrink-0 flex-wrap gap-2">
              <button
                type="button"
                className="secondary-button"
                disabled={testStoredKey.isPending || removeKey.isPending}
                onClick={() => testStoredKey.mutate()}
              >
                {testStoredKey.isPending ? (
                  <Loader2 size={14} className="animate-spin" />
                ) : null}
                Test connection
              </button>
              <button
                type="button"
                className="secondary-button text-rose-600 hover:bg-rose-50 dark:hover:bg-rose-950"
                disabled={removeKey.isPending || testStoredKey.isPending}
                onClick={handleRemove}
                title="Remove API key"
              >
                {removeKey.isPending ? (
                  <Loader2 size={14} className="animate-spin" />
                ) : (
                  <Trash2 size={14} />
                )}
                Remove key
              </button>
            </div>
          </div>
          {!replacing ? (
            <button
              type="button"
              className="mt-3 text-sm font-medium text-accent hover:underline"
              onClick={() => {
                setReplacing(true);
                setApiKey("");
                setVerifiedModel(null);
              }}
            >
              Use a different API key
            </button>
          ) : null}
        </div>
      ) : (
        <p className="mt-5 rounded-xl border border-dashed border-border px-4 py-3 text-sm text-muted">
          No Gemini API key connected yet.
        </p>
      )}

      {showKeyForm ? (
        <div className="mt-5 border-t border-border pt-5">
          <p className="text-sm font-medium text-foreground">
            {hasConnection ? "Replace API key" : "Connect API key"}
          </p>
          <label className="mt-3 block text-sm font-medium">
            API key
            <input
              className="input mt-1 w-full font-mono text-sm"
              type="password"
              autoComplete="off"
              placeholder="AIza…"
              value={apiKey}
              onChange={(e) => {
                setApiKey(e.target.value);
                setVerifiedModel(null);
              }}
            />
          </label>
          <p className="mt-2 text-xs text-muted">
            Test connection automatically picks the best available Gemini model and retries
            fallbacks if needed.
          </p>
          {verifiedModel && pastedKey.length >= 10 ? (
            <p className="mt-2 text-xs text-amber-700 dark:text-amber-300">
              Test passed with {verifiedModel}. Save to apply this key to Ask AI.
            </p>
          ) : null}
          <div className="mt-4 flex flex-wrap gap-2">
            <button
              type="button"
              className="primary-button"
              disabled={pastedKey.length < 10 || save.isPending}
              onClick={() => save.mutate()}
            >
              {save.isPending ? <Loader2 size={14} className="animate-spin" /> : null}
              Save &amp; connect
            </button>
            <button
              type="button"
              className="secondary-button"
              disabled={testPastedKey.isPending || pastedKey.length < 10}
              onClick={handleTestNewKey}
            >
              {testPastedKey.isPending ? <Loader2 size={14} className="animate-spin" /> : null}
              Test connection
            </button>
            {replacing ? (
              <button
                type="button"
                className="secondary-button"
                onClick={() => {
                  setReplacing(false);
                  setApiKey("");
                  setVerifiedModel(null);
                }}
              >
                Cancel
              </button>
            ) : null}
          </div>
        </div>
      ) : null}
    </section>
  );
}

function GeminiMark() {
  return (
    <svg width="28" height="28" viewBox="0 0 28 28" aria-hidden="true" className="shrink-0">
      <defs>
        <linearGradient id="geminiGrad" x1="4" y1="4" x2="24" y2="24" gradientUnits="userSpaceOnUse">
          <stop stopColor="#4E8FF7" />
          <stop offset="0.5" stopColor="#8B6CF6" />
          <stop offset="1" stopColor="#E86BA5" />
        </linearGradient>
      </defs>
      <path
        fill="url(#geminiGrad)"
        d="M14 3c.6 4.8 4.2 8.4 9 9-4.8.6-8.4 4.2-9 9-.6-4.8-4.2-8.4-9-9 4.8-.6 8.4-4.2 9-9Z"
      />
    </svg>
  );
}
